"""各回の生成プロンプトを組み立てる。

素材（コード・実測ログ）はファイルから読んで貼る。手で写さないのは、
本文に載るコードと実際に走ったコードを必ず同一にするため。

指示は短くする。EXP-107 の実測では、仕様が 5,174字 → 7,526字 に伸びたとき
gemma4 の完走率が「3回に1回」に落ち、2,595字に削ったら両モデルとも1発完走に戻った。
そこで文体規約は全文（71行）ではなく要点だけを貼る。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lessons import LESSONS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

MARK_BEGIN = "<<<SECTION>>>"
MARK_END = "<<<END>>>"

STYLE = """## 文体（守ること）

- 句読点は全角の「、」「。」。半角の , . を地の文に使わない（コード内は別）
- 一文は60字を目安、長くても100字まで。接続を重ねない
- 英単語を地の文に生で混ぜない。訳語かカタカナにする
  （例外: Python, Ollama などの固有名詞、コード中の識別子、LLM/API/JSON などの略語）
- 敬体（です・ます）で統一する。同じ文末を3回続けない
- 各節は「この仕組みが無いと何に困るか」を1〜2文書いてから説明に入る。定義から始めない
- コードを見せたら、それが何をしているかを日常語で1文添える
- 数え上げた対象は全部見せる（「道具は3つ」と書くなら3つとも示す）
- 根拠のない数値の閾値を書かない。「〜と言われています」で根拠を省略しない
- 節を「重要です」で締めない。何がどう重要かを書く
- **「素材1」「素材2」という言葉を本文に書かない。**読者はこの指示書を読んでいない
"""

HEAD = """あなたは、プログラミング教材の書き手です。
「LLMエージェント自作講座」（全12回・日本語・Note公開）の**第{n}回**の本文を書いてください。

## 講座の性格

- 読者は Python を書ける初学者。フレームワークは使わず、標準ライブラリだけで組む
- 毎回、実際に手元のローカルモデル（gemma4:e4b）を走らせて、その挙動を観察する
- 第1回=whileループ、第2回=道具を持たせる、第3回=道具を選ばせる、
  第4回=ファイルという身体（読み書きと作業フォルダの関門）、まで済んでいる
- 第{n}回のテーマは「{title}」

## 構成（この順で、この見出しで書く。各節に何を入れるかも守る）

{outline}

## 分量とコードの扱い

- 本文は**6,000字程度**。各節を1段落で済ませない
- コードは**素材からそのまま貼る**。書き直したり、擬似コードにしたりしない。
  長い部分は関係する関数だけ抜き出してよいが、抜き出した行は素材と一字一句同じにする

## 絶対の禁止

**実行結果を自分で書かないこと。** 下に渡した実測ログに無い出力・エラー文・
モデルの回答を、本文に書いてはいけません。ログを引用するときは渡されたものを
そのまま使い、そこで何が起きたかの説明を足してください。
渡していない実験を「やってみました」と書くのも禁止です。
"""

OUTFMT = f"""## 出力の形式

**下書きを書かないでください。** 1文字目を {MARK_BEGIN} にし、最後に {MARK_END} を置きます。
この2つのマーカーの間だけが提出物です。

{MARK_BEGIN}
# タイトル案：LLMエージェント自作講座 第{{n}}回 — （続きを書く）

（ここに本文をMarkdownで。上の構成の見出しを順に）
{MARK_END}
"""


def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8").rstrip()


def build(n=4):
    if n == 4:  # 第4回は EXP-112 のパイロットで使った形をそのまま残す
        return _build_04()
    L = LESSONS[n]
    parts = [HEAD.format(n=n, title=L["title"], outline=L["outline"]), STYLE]
    for i, f in enumerate(L["code"], 1):
        parts += [f"## 素材{i}: 本文に載せるコード（`code/{f}`。この通りに引用すること）",
                  "```python", read(f"code/{f}"), "```"]
    parts += [f"## 素材{len(L['code'])+1}: 実測ログ（これが唯一の実行結果。ここに無いものは書かない）",
              "```", read(f"outputs/{L['log']}"), "```",
              OUTFMT.format(n=n)]
    return "\n".join(parts)


def _build_04():
    from lessons import COMMON_TAIL  # noqa: F401  （第4回は下に直書き）
    outline = """- `## 前回の復習` — 第3回までを3〜4文で
- `## ファイルに書くという身体` — なぜファイルが要るのか。跡が残らない困りごとから入る
- `## 道具を3つ足す（ループは変わらない）` — **素材1から3つの道具の実装を貼る**
- `## 関門：身体の範囲を決める` — **素材1から `safe_path` を貼る**
- `## 実験：エージェントを走らせる` — **素材3から実験1・2・3のログをそのまま貼る**
- `## お願いで守るか、構造で守るか` — **素材3の実験4a と 4b を並べて貼る**
- `## まとめ` — 箇条書き4〜6項目
- `## 練習問題` — **5問**
- `### 解答例` — 5問すべてに答える"""
    return "\n".join([
        HEAD.format(n=4, title="ファイルという身体", outline=outline), STYLE,
        "## 素材1: 本文に載せるコード（`code/04_file_agent.py`）",
        "```python", read("code/04_file_agent.py"), "```",
        "## 素材2: 関門の単体テスト（`code/04_path_guard_test.py`）",
        "```python", read("code/04_path_guard_test.py"), "```",
        "## 素材3: 実測ログ（これが唯一の実行結果。ここに無いものは書かない）",
        "```", read("outputs/04_demo_log.txt"), "```",
        OUTFMT.format(n=4),
    ])


if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    p = build(n)
    out = ROOT / "outputs" / f"{n:02d}_prompt.txt"
    out.write_text(p, encoding="utf-8")
    print(f"第{n}回 プロンプト {len(p):,}字 → {out}")
